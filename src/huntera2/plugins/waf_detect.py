# --- Коды статуса, характерные для WAF-блокировок ---
BLOCK_STATUS_CODES = {401, 403, 405, 406, 407, 429, 418, 503}

# --- Вредоносные payload'ы для активной пробы ---
MALICIOUS_PAYLOADS = [
    ("/?q=<script>alert(1)</script>", "XSS"),
    ("/?id=1' OR '1'='1", "SQLi"),
    ("/?file=../../../../etc/passwd", "LFI"),
    ("/?cmd=;cat /etc/passwd", "RCE"),
]


def _normalize(url: str) -> str:
    if not url.startswith(("http://", "https://")):
        url = "http://" + url
    return url.rstrip("/")


def _match_signatures(headers: dict, cookies: list, body: str) -> dict:
    """Пассивный анализ: заголовки, cookies, тело."""
    found = {}  # name -> set(signals)

    def add(name, signal):
        found.setdefault(name, set()).add(signal)

    # Заголовки
    for header_name, needle, waf_name in WAF_SIGNATURES:
        h = header_name.lower()
        if h == "set-cookie":
            # Проверка cookies
            for c in cookies:
                if needle is None or needle.lower() in c.lower():
                    add(waf_name, f"cookie:{c.split('=')[0]}")
            continue
        if h not in headers:
            continue
        value = headers[h].lower()
        if needle is None or needle.lower() in value:
            add(waf_name, f"header:{header_name}={value[:40]}")

    # Тело
    for pattern, waf_name in BODY_SIGNATURES:
        if re.search(pattern, body, re.IGNORECASE):
            add(waf_name, f"body:{pattern}")

    return found


async def _probe(client, url: str, timeout: float):
    try:
        r = await client.get(url, timeout=timeout, follow_redirects=False)
        return {
            "status": r.status_code,
            "headers": {k.lower(): v for k, v in r.headers.items()},
            "cookies": [c for c in r.headers.get_list("set-cookie")] if hasattr(r.headers, "get_list") else [v for k, v in r.headers.items() if k.lower() == "set-cookie"],
            "body": r.text[:5000],
            "length": len(r.content),
        }
    except Exception as e:
        return {"error": str(e)}


async def _scan_async(url: str, timeout: float, active: bool):
    base = _normalize(url)
    limits = httpx.Limits(max_connections=10, max_keepalive_connections=10)
    headers = {"User-Agent": "Mozilla/5.0 (compatible; HunterA2/0.1)"}

    async with httpx.AsyncClient(limits=limits, headers=headers, verify=False) as client:
        # Нормальный запрос
        normal = await _probe(client, base, timeout)
        if "error" in normal:
            return {"error": normal["error"]}

        passive_found = _match_signatures(normal["headers"], normal["cookies"], normal["body"])

        # Активная проба (если пассив не дал результата и включена)
        active_result = None
        if active and not passive_found:
            for payload, attack_type in MALICIOUS_PAYLOADS:
                probe_url = base + payload
                mal = await _probe(client, probe_url, timeout)
                if "error" in mal:
                    continue
                # Признак WAF: статус изменился на блокирующий ИЛИ длина резко упала
                if mal["status"] in BLOCK_STATUS_CODES and mal["status"] != normal["status"]:
                    active_found = _match_signatures(mal["headers"], mal["cookies"], mal["body"])
                    active_result = {
                        "attack": attack_type,
                        "payload": payload,
                        "normal_status": normal["status"],
                        "blocked_status": mal["status"],
                        "length_drop": normal["length"] - mal["length"],
                        "signatures": {k: list(v) for k, v in active_found.items()},
                    }
                    # Мержим найденные сигнатуры
                    for k, v in active_found.items():
                        passive_found.setdefault(k, set()).update(v)
                    break
                # Если статус тот же, но длина отличается сильно — тоже подозрительно
                if abs(normal["length"] - mal["length"]) > 500:
                    active_result = {
                        "attack": attack_type,
                        "payload": payload,
                        "normal_status": normal["status"],
                        "blocked_status": mal["status"],
                        "length_drop": normal["length"] - mal["length"],
                        "signatures": {},
                        "note": "response length changed significantly",
                    }
                    break

        return {
            "url": base,
            "normal_status": normal["status"],
            "normal_length": normal["length"],
            "detected": {k: sorted(v) for k, v in passive_found.items()},
            "active_probe": active_result,
        }


def _run_scan(url, timeout, active):
    def _worker():
        loop = asyncio.new_event_loop()
        try:
            return loop.run_until_complete(_scan_async(url, timeout, active))
        finally:
            loop.close()
    with concurrent.futures.ThreadPoolExecutor(max_workers=1) as ex:
        return ex.submit(_worker).result()


class WafDetect(Plugin):
    name = "waf_detect"
    description = "Detect and fingerprint WAF: headers, cookies, body, active probes"
    usage = "url=https://example.com [active=1] [timeout=10] [json=1]"
    icon = "🛡"
    cache_ttl = 3600
    category = "Recon"
    needs_network = True

    def run(self, args: dict) -> str:
        if not HTTPX_AVAILABLE:
            return "[#e63946]httpx not installed.[/#e63946]"

        url = args.get("url")
        if not url:
            return "Error: pass url=<https://example.com>"

        active = args.get("active") in ("1", "true", "yes")
        timeout = float(args.get("timeout", "10.0"))
        json_out = args.get("json") in ("1", "true", "yes")

        try:
            result = _run_scan(url, timeout, active)
        except Exception as e:
            return f"[#e63946]Scan error:[/#e63946] {e}"

        if "error" in result:
            return f"[#e63946]Error:[/#e63946] {result['error']}"

        if json_out:
            return json.dumps(result, indent=2, ensure_ascii=False)

        # --- Human-readable ---
        lines = []
        lines.append(f"[b]URL:[/b]       {result['url']}")
        lines.append(f"[b]Status:[/b]    {result['normal_status']}")
        lines.append(f"[b]Length:[/b]    {result['normal_length']} bytes")
        lines.append("")

        detected = result["detected"]
        if detected:
            lines.append(f"[b]◆ WAF Detected:[/b]  [#7fb069]{len(detected)}[/#7fb069]")
            for waf_name, signals in detected.items():
                lines.append(f"  {severity.tag('high')}  [b]{waf_name}[/b]")
                for sig in signals:
                    lines.append(f"    [#8a8a8a]•[/#8a8a8a] {sig}")
            lines.append("")
        else:
            lines.append(f"[b]◆ WAF:[/b]  {severity.tag('ok')}  [#555555]не обнаружен (пассивный анализ)[/#555555]")
            lines.append("")

        # Активная проба
        ap = result.get("active_probe")
        if ap:
            lines.append("[b #e6b800]◆ Active Probe:[/b #e6b800]")
            lines.append(f"  [#8a8a8a]•[/#8a8a8a] Тип атаки: {ap['attack']}")
            lines.append(f"  [#8a8a8a]•[/#8a8a8a] Payload: {ap['payload'][:60]}")
            lines.append(f"  [#8a8a8a]•[/#8a8a8a] Status: {ap['normal_status']} → {ap['blocked_status']}")
            lines.append(f"  [#8a8a8a]•[/#8a8a8a] Δ length: {ap['length_drop']} bytes")
            if ap.get("signatures"):
                lines.append("  [#8a8a8a]Сигнатуры:[/#8a8a8a]")
                for waf_name, sigs in ap["signatures"].items():
                    lines.append(f"    [#e63946]●[/#e63946] {waf_name}")
            if ap.get("note"):
                lines.append(f"  [#555555]ℹ {ap['note']}[/#555555]")

        return "\n".join(lines)


PLUGIN = WafDetect()
